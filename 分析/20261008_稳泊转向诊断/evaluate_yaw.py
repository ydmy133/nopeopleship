"""Counterfactual heading steps on fitted yaw models, using firmware equations.

New trajectories are generated by a plant approximation; measured heading is
never reused as the new controller's response. This is NOT hardware validation.
"""
import itertools
import json
import math
from pathlib import Path
from tune_yaw import ROOT, effective

RAD = math.pi/180


def clamp(x, lo, hi):
    return max(lo, min(hi, x))


class Controller:
    def __init__(self, p):
        self.p = p
        self.desired = self.error = self.integral = 0.0
        self.reset = True

    def update(self, yaw_error_deg, rate_deg, dt):
        p = self.p
        error_angle = (yaw_error_deg+180)%360-180
        requested = p['angle_p']*error_angle*RAD
        cap = math.sqrt(2*abs(error_angle*RAD)*p['accel']*RAD)
        requested = clamp(requested,-cap,cap)
        if self.reset or dt > p.get('timeout_ms',200)/1000:
            self.desired = rate_deg*RAD
            self.integral = 0.0
            self.reset = True
        delta = p['accel']*RAD*dt
        limit = requested <= self.desired-delta or requested >= self.desired+delta
        self.desired = clamp(requested,self.desired-delta,self.desired+delta)
        rate_max = p['max_rate']*RAD
        limit |= self.desired <= -rate_max or self.desired >= rate_max
        self.desired = clamp(self.desired,-rate_max,rate_max)
        raw = self.desired-rate_deg*RAD
        if self.reset:
            self.error = raw
            self.reset = False
        else:
            alpha = dt/(dt+1/(2*math.pi*10))
            self.error += alpha*(raw-self.error)
        grow = not limit or self.integral*self.error < 0
        if grow:
            self.integral = clamp(self.integral+self.error*p['rate_i']*dt,-p['imax'],p['imax'])
        output = p['rate_p']*self.error+self.integral+p['ff']*self.desired
        # Firmware rounds to an integer driver percentage.
        return math.copysign(math.floor(abs(clamp(output,-1,1))*100+.5),output)


OLD = dict(angle_p=2,rate_p=.2,rate_i=.2,ff=.2,imax=1,max_rate=40,accel=30)


def simulate(params, model, initial_error=179, sample=.1, sensor_delay=0, duration=120):
    c = Controller(params)
    # Clockwise error and rate here; driver signs are converted at the boundary.
    yaw = rate = 0.0
    target = initial_error
    output_history = [0.0]
    yaw_history = [0.0]
    rate_history = [0.0]
    errors = []
    outputs = []
    rates = []
    trace = []
    hold = max(0,round(model['delay']/sample))
    sense = max(0,round(sensor_delay/sample))
    alpha = math.exp(-sample/model['tau'])
    for i in range(round(duration/sample)):
        hdg = yaw_history[max(0,len(yaw_history)-1-sense)]
        gyro = rate_history[max(0,len(rate_history)-1-sense)]
        output = c.update(target-hdg,gyro,sample)
        output_history.append(output)
        applied = output_history[max(0,len(output_history)-1-hold)]
        next_rate = alpha*rate+(1-alpha)*(model['gain']*effective(applied,model['deadband'])+model['bias'])
        yaw += (rate+next_rate)*.5*sample
        rate = next_rate
        yaw_history.append(yaw)
        rate_history.append(rate)
        err = (target-yaw+180)%360-180
        errors.append(err)
        outputs.append(output)
        rates.append(rate)
        trace.append(dict(t=round((i+1)*sample,3), error=err, rate=rate, output=output))
    # Unwrapped overshoot distinguishes a full rotation from short-path settling.
    overshoot = max(0,max(yaw_history)-target) if target>0 else max(0,target-min(yaw_history))
    settling = None
    for i in range(len(errors)-1,-1,-1):
        if abs(errors[i])>5 or abs(rates[i])>2:
            if i<len(errors)-1:
                settling=(i+2)*sample
            break
    crossings=sum(x*y<0 and abs(x-y)<180 for x,y in zip(errors,errors[1:]))
    metrics=dict(overshoot_deg=overshoot, peak_rate_dps=max(map(abs,rates)),
                 settling_s=settling, crossings=crossings,
                 final_error_deg=errors[-1], last30_peak_error=max(map(abs,errors[-round(30/sample):])))
    return metrics,trace


def main():
    fitted=json.loads((ROOT/'yaw_model_fit.json').read_text(encoding='utf-8'))['top_fits'][0]
    nominal={k:fitted[k] for k in ('tau','gain','deadband','delay','bias')}
    # Identification used CCW-positive gz; the controller uses CW-positive yaw.
    nominal['bias'] = -nominal['bias']
    candidates=[]
    for ang,pi,ii,limit,accel in itertools.product((.2,.25,.3,.35,.4),(.15,.2,.3),(.02,.03,.05),(10,12,15),(10,15,20)):
        p=dict(angle_p=ang,rate_p=pi,rate_i=ii,ff=.2,imax=.15,max_rate=limit,accel=accel)
        m,_=simulate(p,nominal)
        score=m['overshoot_deg']*2+(m['settling_s'] or 200)+m['last30_peak_error']*5
        candidates.append((score,p,m))
    candidates.sort(key=lambda item:item[0])
    print('nominal old',simulate(OLD,nominal)[0])
    print('top candidates',json.dumps(candidates[:8],indent=2))
    result={'nominal_model':nominal,'baseline_params':OLD,'candidates':candidates[:8]}
    # Test nominal finalists against inertia, delay, bias and cadence uncertainty.
    robustness=[]
    for label,p in [('old',OLD)]+[(f'candidate{i+1}',v[1]) for i,v in enumerate(candidates[:5])]:
        checks=[]
        for tau,gain,delay,sensor_delay,dt,bias in itertools.product((3,4,5),(2.3,2.7,3.1),(0,.3), (0,.2),(.1,.2),(-1,0,1)):
            model=dict(tau=tau,gain=gain,delay=delay,deadband=2,bias=bias)
            m,_=simulate(p,model,sample=dt,sensor_delay=sensor_delay)
            checks.append(m)
        robustness.append(dict(label=label,params=p,scenarios=len(checks),
                               worst_overshoot=max(m['overshoot_deg'] for m in checks),
                               worst_last30_error=max(m['last30_peak_error'] for m in checks),
                               unsettled=sum(m['settling_s'] is None for m in checks)))
    result['robustness']=robustness
    (ROOT/'yaw_candidate_evaluation.json').write_text(json.dumps(result,indent=2),encoding='utf-8')
    print('robustness',json.dumps(robustness,indent=2))


if __name__=='__main__':
    main()
